package io.skipcheck.tm1.codegen;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import java.util.TreeMap;

import io.skipcheck.tm1.csdl.CsdlAnnotation;
import io.skipcheck.tm1.csdl.CsdlDocument;
import io.skipcheck.tm1.csdl.CsdlEntityContainer;
import io.skipcheck.tm1.csdl.CsdlEntityType;
import io.skipcheck.tm1.csdl.CsdlEnumType;
import io.skipcheck.tm1.csdl.CsdlNavigationProperty;
import io.skipcheck.tm1.csdl.CsdlOperation;
import io.skipcheck.tm1.csdl.CsdlParameter;
import io.skipcheck.tm1.csdl.CsdlProperty;
import io.skipcheck.tm1.csdl.CsdlRevision;
import io.skipcheck.tm1.csdl.CsdlSchema;
import io.skipcheck.tm1.csdl.CsdlStructuredType;
import io.skipcheck.tm1.csdl.CsdlTypeRef;
import tools.jackson.core.util.DefaultIndenter;
import tools.jackson.core.util.DefaultPrettyPrinter;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.JsonNodeFactory;
import tools.jackson.databind.node.ObjectNode;

/**
 * Exports the API spec ({@code spec/tm1-api.json}): the {@code $metadata} snapshot as
 * plain JSON, with the {@linkplain Overlay overlay} merged in, for the generators of
 * clients in other languages. It's what every client is generated from, so they share one
 * reading of {@code $metadata}:
 *
 * <ul>
 * <li>{@code enums}, {@code types} and {@code operations}, with descriptions and
 * {@code Core.Revisions} (since, deprecated);</li>
 * <li>{@code container}: entity sets, singletons and imports;</li>
 * <li>{@code endpoints}: the coverage gate's inventory (plan §12.3), the unit every
 * client's coverage is counted in, with the overlay's notes.</li>
 * </ul>
 *
 * <p>
 * Type references are fully qualified ({@code ibm.tm1.api.v1.Cube}) or {@code Edm.*};
 * operations carry the name they're called by in a path ({@code tm1.Reserve}). Lists are
 * sorted, so the file diffs cleanly when the snapshot changes. The format is versioned by
 * {@code specVersion}.
 */
public final class ApiSpecExporter {

	/** The version of the spec's format. */
	public static final int SPEC_VERSION = 1;

	private static final JsonNodeFactory JSON = JsonNodeFactory.instance;

	private final CsdlDocument metadata;

	private final Overlay overlay;

	private final String snapshot;

	/**
	 * An exporter.
	 * @param metadata the {@code $metadata} snapshot
	 * @param overlay what TM1 does differently from it
	 * @param snapshot the snapshot's file name, recorded in the spec
	 */
	public ApiSpecExporter(CsdlDocument metadata, Overlay overlay, String snapshot) {
		this.metadata = Objects.requireNonNull(metadata, "metadata");
		this.overlay = Objects.requireNonNull(overlay, "overlay");
		this.snapshot = Objects.requireNonNull(snapshot, "snapshot");
	}

	/**
	 * The spec as JSON text: tab-indented, with a final newline.
	 * @return the text
	 * @throws IllegalArgumentException if the overlay names a property or endpoint the
	 * snapshot doesn't have
	 */
	public String export() {
		ObjectNode root = JSON.objectNode();
		root.put("$comment",
				"Generated by tm1-codegen from the $metadata snapshot and spec/tm1-overlay.json: don't edit. Regenerate with ./gradlew :tm1-codegen:exportSpec");
		root.put("specVersion", SPEC_VERSION);
		ObjectNode source = root.putObject("source");
		source.put("snapshot", snapshot);
		source.put("schemaVersion", metadata.schemaVersion().orElse(null));
		source.put("odataVersion", metadata.version());
		ArrayNode schemas = root.putArray("schemas");
		for (CsdlSchema schema : metadata.schemas()) {
			schemas.addObject().put("namespace", schema.namespace()).put("alias", schema.alias());
		}
		root.set("enums", enums());
		root.set("types", types());
		root.set("operations", operations());
		metadata.entityContainer().ifPresent(c -> root.set("container", container(c)));
		root.set("endpoints", endpoints());
		DefaultPrettyPrinter printer = new DefaultPrettyPrinter().withObjectIndenter(new DefaultIndenter("\t", "\n"))
			.withArrayIndenter(new DefaultIndenter("\t", "\n"));
		return JsonMapper.builder().build().writer().with(printer).writeValueAsString(root) + "\n";
	}

	private ArrayNode enums() {
		ArrayNode out = JSON.arrayNode();
		for (CsdlSchema schema : metadata.schemas()) {
			schema.enumTypes().stream().sorted(Comparator.comparing(CsdlEnumType::name)).forEach(e -> {
				ObjectNode node = out.addObject();
				node.put("name", e.name());
				node.put("qualifiedName", schema.namespace() + "." + e.name());
				node.put("literalPrefix", prefix(schema) + e.name());
				node.put("underlyingType", e.underlyingType());
				node.put("flags", e.flags());
				docs(node, e.annotations());
				ArrayNode members = node.putArray("members");
				for (CsdlEnumType.Member m : e.members()) {
					ObjectNode member = members.addObject().put("name", m.name()).put("value", m.value());
					docs(member, m.annotations());
				}
			});
		}
		return out;
	}

	private ArrayNode types() {
		ArrayNode out = JSON.arrayNode();
		Map<String, List<String>> derived = new TreeMap<>();
		metadata.structuredTypes().forEach(t -> {
			if (t.baseType() != null) {
				derived.computeIfAbsent(metadata.qualify(Objects.requireNonNull(t.baseType())), k -> new ArrayList<>())
					.add(qualified(t));
			}
		});
		Set<String> lenientUsed = new LinkedHashSet<>();
		Set<String> departuresUsed = new LinkedHashSet<>();
		metadata.structuredTypes().sorted(Comparator.comparing(CsdlStructuredType::name)).forEach(t -> {
			ObjectNode node = out.addObject();
			node.put("name", t.name());
			node.put("qualifiedName", qualified(t));
			node.put("kind", t instanceof CsdlEntityType ? "entity" : "complex");
			node.put("baseType", t.baseType() == null ? null : metadata.qualify(Objects.requireNonNull(t.baseType())));
			node.put("abstract", t.isAbstract());
			node.put("open", t.openType());
			if (t instanceof CsdlEntityType entity) {
				node.put("hasStream", entity.hasStream());
				ArrayNode key = node.putArray("key");
				// The key is declared on the root of a hierarchy
				for (CsdlStructuredType level : metadata.typeHierarchy(qualified(t))) {
					if (level instanceof CsdlEntityType e && !e.key().isEmpty()) {
						e.key().forEach(key::add);
						break;
					}
				}
			}
			ArrayNode subtypes = node.putArray("derivedTypes");
			derived.getOrDefault(qualified(t), List.of()).stream().sorted().forEach(subtypes::add);
			docs(node, t.annotations());
			ArrayNode properties = node.putArray("properties");
			for (CsdlProperty p : t.properties()) {
				String key = t.name() + "/" + p.name();
				ObjectNode property = properties.addObject().put("name", p.name());
				type(property, p.type());
				property.put("nullable", p.nullable());
				if (p.defaultValue() != null) {
					property.put("default", p.defaultValue());
				}
				docs(property, p.annotations());
				String departure = overlay.departures().get(key);
				if (departure != null) {
					property.putObject("departure").put("read", "json").put("note", departure);
					departuresUsed.add(key);
				}
				String lenient = overlay.lenientDates().get(key);
				if (lenient != null) {
					property.putObject("lenientDate").put("note", lenient);
					lenientUsed.add(key);
				}
			}
			ArrayNode navigation = node.putArray("navigationProperties");
			for (CsdlNavigationProperty n : t.navigationProperties()) {
				ObjectNode nav = navigation.addObject().put("name", n.name());
				type(nav, n.type());
				nav.put("nullable", n.nullable()).put("containsTarget", n.containsTarget()).put("partner", n.partner());
				docs(nav, n.annotations());
			}
		});
		unused("departures", overlay.departures().keySet(), departuresUsed);
		unused("lenientDates", overlay.lenientDates().keySet(), lenientUsed);
		return out;
	}

	private ArrayNode operations() {
		ArrayNode out = JSON.arrayNode();
		for (CsdlSchema schema : metadata.schemas()) {
			schema.operations().stream().sorted(Comparator.comparing(ApiSpecExporter::operationId)).forEach(op -> {
				ObjectNode node = out.addObject();
				node.put("kind", op.kind() == CsdlOperation.Kind.ACTION ? "action" : "function");
				node.put("name", op.name());
				node.put("qualifiedName", schema.namespace() + "." + op.name());
				node.put("pathName", prefix(schema) + op.name());
				node.put("bound", op.bound());
				if (op.bound()) {
					type(node.putObject("binding"), op.bindingType().orElseThrow());
					node.put("endpoint", endpointId(op));
				}
				node.put("composable", op.composable());
				ArrayNode parameters = node.putArray("parameters");
				for (CsdlParameter p : op.callerParameters()) {
					ObjectNode parameter = parameters.addObject().put("name", p.name());
					type(parameter, p.type());
					parameter.put("nullable", p.nullable());
					docs(parameter, p.annotations());
				}
				if (op.returnType() != null) {
					ObjectNode returns = node.putObject("returns");
					type(returns, Objects.requireNonNull(op.returnType()));
					returns.put("nullable", op.returnNullable());
				}
				else {
					node.putNull("returns");
				}
				docs(node, op.annotations());
			});
		}
		return out;
	}

	private ObjectNode container(CsdlEntityContainer c) {
		ObjectNode node = JSON.objectNode();
		node.put("name", c.name());
		ArrayNode sets = node.putArray("entitySets");
		c.entitySets().stream().sorted(Comparator.comparing(CsdlEntityContainer.EntitySet::name)).forEach(s -> {
			ObjectNode set = sets.addObject().put("name", s.name()).put("entityType", metadata.qualify(s.entityType()));
			bindings(set, s.navigationBindings());
			docs(set, s.annotations());
		});
		ArrayNode singletons = node.putArray("singletons");
		c.singletons().stream().sorted(Comparator.comparing(CsdlEntityContainer.Singleton::name)).forEach(s -> {
			ObjectNode single = singletons.addObject().put("name", s.name()).put("type", metadata.qualify(s.type()));
			bindings(single, s.navigationBindings());
			docs(single, s.annotations());
		});
		ArrayNode actions = node.putArray("actionImports");
		c.actionImports().stream().sorted(Comparator.comparing(CsdlEntityContainer.ActionImport::name)).forEach(i -> {
			ObjectNode imp = actions.addObject().put("name", i.name()).put("operation", metadata.qualify(i.action()));
			imp.put("entitySet", i.entitySet());
			docs(imp, i.annotations());
		});
		ArrayNode functions = node.putArray("functionImports");
		c.functionImports()
			.stream()
			.sorted(Comparator.comparing(CsdlEntityContainer.FunctionImport::name))
			.forEach(i -> {
				ObjectNode imp = functions.addObject()
					.put("name", i.name())
					.put("operation", metadata.qualify(i.function()));
				imp.put("entitySet", i.entitySet());
				docs(imp, i.annotations());
			});
		return node;
	}

	private static void bindings(ObjectNode node, Map<String, String> bindings) {
		ObjectNode out = node.putObject("navigationBindings");
		new TreeMap<>(bindings).forEach(out::put);
	}

	/** The coverage gate's inventory, in the gate's order (by ID), with overlay notes. */
	private ArrayNode endpoints() {
		Map<String, ObjectNode> byId = new TreeMap<>();
		metadata.entityContainer().ifPresent(c -> {
			c.entitySets()
				.forEach(s -> byId.put("EntitySet " + s.name(),
						endpoint("EntitySet " + s.name(), "EntitySet").put("name", s.name())
							.put("type", metadata.qualify(s.entityType()))));
			c.singletons()
				.forEach(s -> byId.put("Singleton " + s.name(),
						endpoint("Singleton " + s.name(), "Singleton").put("name", s.name())
							.put("type", metadata.qualify(s.type()))));
			c.actionImports()
				.forEach(i -> byId.put("ActionImport " + i.name(),
						endpoint("ActionImport " + i.name(), "ActionImport").put("name", i.name())
							.put("operation", metadata.qualify(i.action()))));
			c.functionImports()
				.forEach(i -> byId.put("FunctionImport " + i.name(),
						endpoint("FunctionImport " + i.name(), "FunctionImport").put("name", i.name())
							.put("operation", metadata.qualify(i.function()))));
		});
		for (CsdlSchema schema : metadata.schemas()) {
			for (CsdlOperation op : schema.operations()) {
				if (op.bound()) {
					CsdlTypeRef binding = op.bindingType().orElseThrow();
					ObjectNode node = endpoint(endpointId(op),
							op.kind() == CsdlOperation.Kind.ACTION ? "Action" : "Function")
						.put("name", op.name());
					type(node.putObject("binding"), binding);
					byId.put(endpointId(op), node);
				}
			}
		}
		metadata.structuredTypes()
			.forEach(t -> t.navigationProperties()
				.forEach(n -> byId.put("Navigation " + t.name() + "/" + n.name(),
						endpoint("Navigation " + t.name() + "/" + n.name(), "Navigation").put("owner", qualified(t))
							.put("ownerKind", t instanceof CsdlEntityType ? "entity" : "complex")
							.put("name", n.name()))));
		Set<String> unknown = new LinkedHashSet<>(overlay.endpoints().keySet());
		unknown.removeAll(byId.keySet());
		if (!unknown.isEmpty()) {
			throw new IllegalArgumentException("The overlay notes endpoints $metadata doesn't have: " + unknown);
		}
		ArrayNode out = JSON.arrayNode();
		byId.forEach((id, node) -> {
			Overlay.EndpointNote note = overlay.endpoints().get(id);
			if (note != null) {
				if (note.note() != null) {
					node.put("note", note.note());
				}
				if (!note.forbid().isEmpty()) {
					ArrayNode forbid = node.putArray("forbid");
					note.forbid().forEach(forbid::add);
				}
			}
			out.add(node);
		});
		return out;
	}

	private static ObjectNode endpoint(String id, String kind) {
		return JSON.objectNode().put("id", id).put("kind", kind);
	}

	private static String endpointId(CsdlOperation op) {
		CsdlTypeRef binding = op.bindingType().orElseThrow();
		String type = simple(binding.name());
		return (op.kind() == CsdlOperation.Kind.ACTION ? "Action " : "Function ")
				+ (binding.collection() ? "Collection(" + type + ")" : type) + "/" + op.name();
	}

	private static String operationId(CsdlOperation op) {
		return op.bound() ? endpointId(op) : "~" + op.name();
	}

	private void type(ObjectNode node, CsdlTypeRef ref) {
		node.put("type", ref.name().startsWith("Edm.") ? ref.name() : metadata.qualify(ref.name()));
		node.put("collection", ref.collection());
	}

	/**
	 * {@code description}, {@code longDescription}, {@code since} and {@code deprecated}.
	 */
	private static void docs(ObjectNode node, List<CsdlAnnotation> annotations) {
		text(annotations, "Core.Description").ifPresent(d -> node.put("description", d));
		text(annotations, "Core.LongDescription").ifPresent(d -> node.put("longDescription", d));
		CsdlRevision.addedIn(annotations).ifPresent(v -> node.put("since", v));
		CsdlRevision.deprecatedIn(annotations).ifPresent(v -> {
			ObjectNode deprecated = node.putObject("deprecated").put("version", v);
			CsdlRevision.of(annotations)
				.stream()
				.filter(r -> r.kind() == CsdlRevision.Kind.DEPRECATED && r.description() != null)
				.findFirst()
				.ifPresent(r -> deprecated.put("reason", Objects.requireNonNull(r.description()).strip()));
		});
	}

	private static Optional<String> text(List<CsdlAnnotation> annotations, String term) {
		return CsdlAnnotation.find(annotations, term)
			.flatMap(a -> a.value().asText())
			.map(String::strip)
			.filter(s -> !s.isEmpty());
	}

	private static void unused(String section, Set<String> keys, Set<String> used) {
		Set<String> unknown = new LinkedHashSet<>(keys);
		unknown.removeAll(used);
		if (!unknown.isEmpty()) {
			throw new IllegalArgumentException(
					"The overlay's " + section + " name properties $metadata doesn't have: " + unknown);
		}
	}

	private String qualified(CsdlStructuredType type) {
		return metadata.qualifiedName(type).orElse(type.name());
	}

	private static String prefix(CsdlSchema schema) {
		return (schema.alias() != null ? schema.alias() : schema.namespace()) + ".";
	}

	private static String simple(String qualifiedName) {
		return qualifiedName.substring(qualifiedName.lastIndexOf('.') + 1);
	}

}
