package io.skipcheck.tm1.probe;

import java.util.Collections;
import java.util.Map;
import java.util.NavigableMap;
import java.util.NavigableSet;
import java.util.TreeMap;
import java.util.TreeSet;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.SerializationFeature;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ObjectNode;

/**
 * What a probe found: the file written beside the {@code $metadata} snapshot,
 * {@code tm1-probe-<schema version>.json}. Everything in it is sorted and nothing depends
 * on when or where it ran, so probing the same server twice writes the same file, and a
 * new version's file diffs readably against the last.
 *
 * @param productVersion the server's {@code ProductVersion}, such as {@code 11.8.03500.6}
 * @param schemaVersion its {@code $metadata}'s {@code Core.SchemaVersion}, such as
 * {@code 11.8.35}
 * @param binarySha256 the SHA-256 of the binary the candidates came from
 * @param candidates how many candidate names were tried
 * @param undeclared per entity type (simple name), the properties TM1 accepts in
 * {@code $select} that {@code $metadata} doesn't declare, each with the kind of JSON
 * value the probe read ({@code string}, {@code number}, {@code boolean}, {@code array},
 * {@code object}, {@code null}, {@code navigation}, or {@code unread})
 * @param declaredRefused per entity type, declared properties TM1 refused in
 * {@code $select}
 * @param unverifiable entity types TM1 doesn't check {@code $select} names for, so they
 * may have undeclared properties the probe can't see
 * @param unreached entity types the probe found no path to
 * @param writes per write case, what TM1 does with each property in a POST and a PATCH
 * ({@link WriteProbe})
 * @param collections per collection case, what a PATCH of the collection does
 */
public record ProbeReport(String productVersion, String schemaVersion, String binarySha256, int candidates,
		NavigableMap<String, NavigableMap<String, String>> undeclared,
		NavigableMap<String, NavigableSet<String>> declaredRefused, NavigableSet<String> unverifiable,
		NavigableSet<String> unreached, NavigableMap<String, JsonNode> writes,
		NavigableMap<String, JsonNode> collections) {

	/** The format's version; a reader refuses one it doesn't know. */
	public static final int PROBE_VERSION = 2;

	private static final JsonMapper JSON = JsonMapper.builder().enable(SerializationFeature.INDENT_OUTPUT).build();

	/** Copies the collections, sorted. */
	public ProbeReport {
		NavigableMap<String, NavigableMap<String, String>> u = new TreeMap<>();
		undeclared.forEach((t, p) -> u.put(t, Collections.unmodifiableNavigableMap(new TreeMap<>(p))));
		undeclared = Collections.unmodifiableNavigableMap(u);
		NavigableMap<String, NavigableSet<String>> r = new TreeMap<>();
		declaredRefused.forEach((t, p) -> r.put(t, Collections.unmodifiableNavigableSet(new TreeSet<>(p))));
		declaredRefused = Collections.unmodifiableNavigableMap(r);
		unverifiable = Collections.unmodifiableNavigableSet(new TreeSet<>(unverifiable));
		unreached = Collections.unmodifiableNavigableSet(new TreeSet<>(unreached));
		writes = Collections.unmodifiableNavigableMap(new TreeMap<>(writes));
		collections = Collections.unmodifiableNavigableMap(new TreeMap<>(collections));
	}

	/**
	 * The file's name for a schema version.
	 * @param schemaVersion such as {@code 11.8.35}
	 * @return such as {@code tm1-probe-11.8.35.json}
	 */
	public static String fileName(String schemaVersion) {
		return "tm1-probe-" + schemaVersion + ".json";
	}

	/**
	 * The report as the file holds it.
	 * @return indented JSON, ending with a newline
	 */
	public String toJson() {
		ObjectNode root = JSON.createObjectNode();
		root.put("$comment",
				"Generated by ./gradlew probeTm1 from a running TM1 (java/tools/tm1-probe): don't edit. What TM1 does that its $metadata doesn't say.");
		root.put("probeVersion", PROBE_VERSION);
		ObjectNode server = root.putObject("server");
		server.put("productVersion", productVersion);
		server.put("schemaVersion", schemaVersion);
		ObjectNode binary = root.putObject("binary");
		binary.put("file", "bin64/tm1s.exe");
		binary.put("sha256", binarySha256);
		binary.put("candidates", candidates);
		ObjectNode u = root.putObject("undeclared");
		undeclared.forEach((type, properties) -> {
			ObjectNode t = u.putObject(type);
			properties.forEach((name, kind) -> t.putObject(name).put("json", kind));
		});
		ObjectNode r = root.putObject("declaredRefused");
		declaredRefused.forEach((type, names) -> names.forEach(r.putArray(type)::add));
		unverifiable.forEach(root.putArray("unverifiable")::add);
		unreached.forEach(root.putArray("unreached")::add);
		ObjectNode w = root.putObject("writes");
		writes.forEach(w::set);
		ObjectNode c = root.putObject("collections");
		collections.forEach(c::set);
		return JSON.writeValueAsString(root) + "\n";
	}

	/**
	 * A report read back from its file, to probe the writes again on its findings
	 * ({@link Tm1Probe#runWrites}).
	 * @param json a report file's content
	 * @return the report
	 * @throws IllegalArgumentException if the file's {@code probeVersion} isn't this one
	 */
	public static ProbeReport fromJson(String json) {
		JsonNode root = JSON.readTree(json);
		int version = root.path("probeVersion").asInt();
		if (version != PROBE_VERSION) {
			throw new IllegalArgumentException("Can't read probeVersion " + version + "; this reads " + PROBE_VERSION);
		}
		NavigableMap<String, NavigableMap<String, String>> undeclared = new TreeMap<>();
		for (Map.Entry<String, JsonNode> type : root.path("undeclared").properties()) {
			NavigableMap<String, String> properties = new TreeMap<>();
			type.getValue().properties().forEach(p -> properties.put(p.getKey(), p.getValue().path("json").asString()));
			undeclared.put(type.getKey(), properties);
		}
		NavigableMap<String, NavigableSet<String>> refused = new TreeMap<>();
		for (Map.Entry<String, JsonNode> type : root.path("declaredRefused").properties()) {
			NavigableSet<String> names = new TreeSet<>();
			type.getValue().forEach(n -> names.add(n.asString()));
			refused.put(type.getKey(), names);
		}
		NavigableSet<String> unverifiable = new TreeSet<>();
		root.path("unverifiable").forEach(n -> unverifiable.add(n.asString()));
		NavigableSet<String> unreached = new TreeSet<>();
		root.path("unreached").forEach(n -> unreached.add(n.asString()));
		NavigableMap<String, JsonNode> writes = new TreeMap<>();
		root.path("writes").properties().forEach(e -> writes.put(e.getKey(), e.getValue()));
		NavigableMap<String, JsonNode> collections = new TreeMap<>();
		root.path("collections").properties().forEach(e -> collections.put(e.getKey(), e.getValue()));
		JsonNode server = root.path("server");
		JsonNode binary = root.path("binary");
		return new ProbeReport(server.path("productVersion").asString(), server.path("schemaVersion").asString(),
				binary.path("sha256").asString(), binary.path("candidates").asInt(), undeclared, refused, unverifiable,
				unreached, writes, collections);
	}

	/**
	 * This report with the writes of a new run in place of its own.
	 * @param result what a {@link WriteProbe} found
	 * @return the report
	 */
	public ProbeReport withWrites(WriteProbe.Result result) {
		return new ProbeReport(productVersion, schemaVersion, binarySha256, candidates, undeclared, declaredRefused,
				unverifiable, unreached, result.writes(), result.collections());
	}

	/**
	 * The undeclared property names in a report file, to try again in the next probe
	 * whatever the binary holds.
	 * @param json a report file's content
	 * @return the names, of every type
	 * @throws IllegalArgumentException if the file's {@code probeVersion} isn't known
	 */
	public static NavigableSet<String> undeclaredNames(String json) {
		JsonNode root = JSON.readTree(json);
		int version = root.path("probeVersion").asInt();
		// Version 1 had no writes; its undeclared properties read the same
		if (version < 1 || version > PROBE_VERSION) {
			throw new IllegalArgumentException(
					"Unknown probeVersion " + version + "; this reads 1 to " + PROBE_VERSION);
		}
		NavigableSet<String> names = new TreeSet<>();
		for (Map.Entry<String, JsonNode> type : root.path("undeclared").properties()) {
			type.getValue().propertyNames().forEach(names::add);
		}
		return names;
	}

}
